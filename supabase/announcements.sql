create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 100),
  body text not null check (char_length(body) between 1 and 3000),
  published boolean not null default true,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.announcements enable row level security;
drop policy if exists "Published announcements are public" on public.announcements;
create policy "Published announcements are public" on public.announcements for select to anon, authenticated using (published = true);
grant select on public.announcements to anon, authenticated;

create or replace function public.surelin_publish_announcement(p_title text, p_body text)
returns bigint
language plpgsql
security definer
set search_path = public
as $announcement$
declare
  actor_username text;
  new_id bigint;
begin
  select lower(coalesce(
    (select username from public.profiles where id = auth.uid()),
    (select raw_user_meta_data->>'username' from auth.users where id = auth.uid())
  )) into actor_username;
  if actor_username not in ('isaacgoated', 'rawbt') then
    raise exception 'Only isaacgoated and rawbt can publish announcements';
  end if;
  if char_length(trim(p_title)) not between 1 and 100 then raise exception 'Title must be 1 to 100 characters'; end if;
  if char_length(trim(p_body)) not between 1 and 3000 then raise exception 'Announcement must be 1 to 3000 characters'; end if;
  insert into public.announcements(title, body, created_by)
  values (trim(p_title), trim(p_body), auth.uid())
  returning id into new_id;
  return new_id;
end;
$announcement$;

create or replace function public.surelin_delete_announcement(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $announcement$
declare
  actor_username text;
begin
  select lower(coalesce(
    (select username from public.profiles where id = auth.uid()),
    (select raw_user_meta_data->>'username' from auth.users where id = auth.uid())
  )) into actor_username;
  if actor_username not in ('isaacgoated', 'rawbt') then
    raise exception 'Only isaacgoated and rawbt can manage announcements';
  end if;
  delete from public.announcements where id = p_id;
end;
$announcement$;

revoke all on function public.surelin_publish_announcement(text, text) from public;
revoke all on function public.surelin_delete_announcement(bigint) from public;
grant execute on function public.surelin_publish_announcement(text, text) to authenticated;
grant execute on function public.surelin_delete_announcement(bigint) to authenticated;
